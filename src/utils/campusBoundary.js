/**
 * True jika titik berada di dalam polygon kampus.
 * Algoritma ray casting (even-odd), identik dengan CampusBoundary.contains di Flutter.
 */
function isInsideCampus(latitude, longitude) {
  const x = Number(longitude);
  const y = Number(latitude);
  if (!Number.isFinite(x) || !Number.isFinite(y)) return false;

  let inside = false;
  for (let i = 0, j = CAMPUS_POLYGON.length - 1; i < CAMPUS_POLYGON.length; j = i++) {
    const [aLat, aLng] = CAMPUS_POLYGON[i];
    const [bLat, bLng] = CAMPUS_POLYGON[j];
    if (aLat > y !== bLat > y && x < aLng + ((y - aLat) / (bLat - aLat)) * (bLng - aLng)) {
      inside = !inside;
    }
  }
  return inside;
}

